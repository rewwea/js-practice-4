// WHILE — ЗАДАНИЕ 1
//
// Вывести # столько раз, сколько указал пользователь.
//
// Тут все просто, сначала через prompt спрашиваю сколько раз
// надо вывести решетку. Потом создаю пустую строку symbols,
// куда буду эти решетки добавлять.
//
// i это обычный счетчик, сначала он 0.
// Пока i меньше count, добавляю одну # и увеличиваю i на 1.
// В конце вывожу уже готовую строку через alert.

let count = Number(prompt('WHILE - Задание 1. Сколько символов # вывести?'))

let i = 0
let symbols = ''

while (i < count) {
	symbols += '#'
	i++
}

alert(symbols)

// WHILE — ЗАДАНИЕ 2
//
// Пользователь ввел число, а на экран вывелись все числа
// от введенного до 0.
//
// Тут получаю число от пользователя и делаю пустую строку,
// куда будут записываться все числа.
//
// В while проверяю, чтобы число было больше или равно 0.
// Каждый проход добавляю текущее число в строку и через --
// уменьшаю его на единицу. Так оно постепенно доходит до нуля.

let number = Number(prompt('WHILE - Задание 2. Введите число:'))

let numbers = ''

while (number >= 0) {
	numbers += number + ' '
	number--
}

alert(numbers)

// WHILE — ЗАДАНИЕ 3
//
// Запросить число и степень. Возвести число в указанную
// степень и вывести результат.
//
// Тут специально не использую **, потому что задание именно
// на while и надо показать цикл.
//
// Получаю само число base и степень degree.
// result изначально 1, потому что потом я умножаю его на base.
// Сколько указали степень, столько раз цикл и умножит число
// само на себя.

let base = Number(prompt('WHILE - Задание 3. Введите число:'))
let degree = Number(prompt('Введите степень:'))

let powerResult = 1
let powerCounter = 0

while (powerCounter < degree) {
	powerResult *= base
	powerCounter++
}

alert('Результат: ' + powerResult)

// WHILE — ЗАДАНИЕ 4
//
// Запросить 2 числа и найти все общие делители.
//
// Сначала получаю два числа. Дальше мне надо перебирать
// возможные делители, поэтому divisor начинается с 1.
//
// Еще нахожу меньшее из двух чисел, потому что нет смысла
// проверять делители дальше меньшего числа.
//
// В цикле через % проверяю, делятся ли ОБА числа на divisor
// без остатка. Если да, значит делитель общий и я добавляю
// его в строку commonDivisors.

let firstNumber = Number(prompt('WHILE - Задание 4. Введите первое число:'))
let secondNumber = Number(prompt('Введите второе число:'))

let divisor = 1
let commonDivisors = ''

let minNumber

if (firstNumber < secondNumber) {
	minNumber = firstNumber
} else {
	minNumber = secondNumber
}

while (divisor <= minNumber) {
	if (firstNumber % divisor === 0 && secondNumber % divisor === 0) {
		commonDivisors += divisor + ' '
	}

	divisor++
}

alert('Общие делители: ' + commonDivisors)

// WHILE — ЗАДАНИЕ 5
//
// Посчитать факториал введенного пользователем числа.
//
// Факториал это когда перемножаются все числа от 1 до самого
// введенного числа. Например 5! = 1 * 2 * 3 * 4 * 5.
//
// factorial начинаю с 1, а factorialCounter тоже с 1.
// Потом в каждом проходе умножаю factorial на счетчик
// и увеличиваю счетчик. Когда дошли до введенного числа,
// цикл заканчивается.

let factorialNumber = Number(prompt('WHILE - Задание 5. Введите число:'))

let factorial = 1
let factorialCounter = 1

while (factorialCounter <= factorialNumber) {
	factorial *= factorialCounter
	factorialCounter++
}

alert('Факториал числа: ' + factorial)

// DO WHILE — ЗАДАНИЕ 1
//
// Предлагать пользователю решить пример 2 + 2 * 2 до тех
// пор, пока он не решит его правильно.
//
// Тут уже нужен do while. Его прикол в том, что код внутри do
// в любом случае выполнится хотя бы один раз.
//
// Сначала спрашиваю ответ. Если ответ не 6, пишу что неправильно.
// Потом while опять проверяет answer и если там не 6,
// запускает все заново.
//
// Почему ответ 6: сначала по приоритету идет умножение
// 2 * 2 = 4, потом 2 + 4 = 6.

let answer

do {
	answer = Number(prompt('DO WHILE - Задание 1. Решите пример: 2 + 2 * 2 = ?'))

	if (answer !== 6) {
		alert('Неправильно. Попробуйте еще раз.')
	}
} while (answer !== 6)

alert('Правильно!')

// DO WHILE — ЗАДАНИЕ 2
//
// Делить число 1000 на 2 до тех пор, пока не получится число
// меньше 50. Вывести это число и сколько делений произвели.
//
// value сначала равно 1000.
// divisionCount нужен просто чтобы считать количество делений.
//
// Каждый проход делю value на 2 и прибавляю к счетчику 1.
// Цикл работает пока value больше или равно 50.
// Как только стало меньше 50, выходим и показываем результат.

let value = 1000
let divisionCount = 0

do {
	value = value / 2
	divisionCount++
} while (value >= 50)

alert('Полученное число: ' + value + '\nКоличество делений: ' + divisionCount)

// FOR — ЗАДАНИЕ 1
//
// Вывести все числа от 1 до 100, которые кратные указанному
// пользователем числу.
//
// Получаю число multiple. Дальше for перебирает вообще все
// числа от 1 до 100.
//
// Через % смотрю остаток от деления.
// Если i % multiple дает 0, значит число делится без остатка
// и оно кратно введенному числу. Тогда добавляю его в строку.

let multiple = Number(prompt('FOR - Задание 1. Введите число:'))

let multipleNumbers = ''

for (let i = 1; i <= 100; i++) {
	if (i % multiple === 0) {
		multipleNumbers += i + ' '
	}
}

alert('Кратные числа от 1 до 100:\n' + multipleNumbers)

// FOR — ЗАДАНИЕ 2
//
// Вывести каждый 4-й элемент из указанного пользователем
// диапазона. Пользователь указывает минимальное и максимальное
// значения диапазона.
//
// Тут спрашиваю начало диапазона min и конец max.
//
// В for начинаю сразу с min. Обычно пишется i++, то есть
// прибавляется по одному, но мне нужен каждый четвертый элемент,
// поэтому тут просто делаю i += 4.
//
// Например от 10 до 30 получится:
// 10 14 18 22 26 30

let min = Number(
	prompt('FOR - Задание 2. Введите минимальное значение диапазона:'),
)
let max = Number(prompt('Введите максимальное значение диапазона:'))

let rangeResult = ''

for (let i = min; i <= max; i += 4) {
	rangeResult += i + ' '
}

alert('Каждый 4-й элемент диапазона:\n' + rangeResult)

// FOR — ЗАДАНИЕ 3
//
// Запросить число и проверить, простое ли оно.
// Простое число делится без остатка только на себя и на единицу.
//
// Сначала считаю, что число простое, поэтому isPrime = true.
//
// Если число 1, 0 или вообще отрицательное, оно сразу не простое.
//
// Если число больше 1, циклом начинаю проверять делители с 2.
// Через % смотрю, делится ли число без остатка.
//
// Если хотя бы один такой делитель нашелся, ставлю false.
// break нужен чтобы сразу выйти из цикла, потому что дальше
// уже проверять смысла нет — мы уже поняли что число не простое.

let primeNumber = Number(prompt('FOR - Задание 3. Введите число:'))

let isPrime = true

if (primeNumber <= 1) {
	isPrime = false
} else {
	for (let i = 2; i < primeNumber; i++) {
		if (primeNumber % i === 0) {
			isPrime = false
			break
		}
	}
}

if (isPrime) {
	alert('Число ' + primeNumber + ' является простым')
} else {
	alert('Число ' + primeNumber + ' не является простым')
}
